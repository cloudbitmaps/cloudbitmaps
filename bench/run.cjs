function inject(rel, regions) {
  // Line endings are not content: a checkout that turns them into CRLF must not fail the check.
  let s = fs.readFileSync(path.join(ROOT, rel), 'utf8').replace(/\r\n/g, '\n');
  for (const [name, body] of Object.entries(regions)) s = replaceRegion(s, name, body, rel);
  put(rel, s);
}
function replaceRegion(s, name, body, rel) {
  const start = `<!-- BENCH:${name}:START -->`;
  const end = `<!-- BENCH:${name}:END -->`;
  const i = s.indexOf(start);
  const j = s.indexOf(end);
  // Throwing rather than warning is deliberate: a silently-skipped region publishes a page with a stale or
  // empty figure, which is worse than a failed run. This is exactly how the site rebuild broke `pnpm bench` —
  // the markers were dropped with the old markup and nothing noticed until the next run.
  if (i === -1 || j === -1 || j < i) throw new Error(`missing BENCH:${name} markers in ${rel}`);
  if (s.indexOf(start, i + 1) !== -1 || s.indexOf(end, j + 1) !== -1) {
    throw new Error(`more than one BENCH:${name} region in ${rel}`);
  }
  return s.slice(0, i + start.length) + '\n' + body + '\n' + s.slice(j);
}
function write(rel, body) {
  put(rel, body);
}
/** Write a file, or under `--check` compare it with what is on disk and remember it if they differ. */
function put(rel, body) {
  const file = path.join(ROOT, rel);
  if (check) {
    const now = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null;
    if (now !== body) stale.push(rel);
    return;
  }
  fs.writeFileSync(file, body);
  log(rel);
}
function esc(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}
function round(n, d) {
  const f = 10 ** d;
  return Math.round(n * f) / f;
}
function log(rel) {
  console.log(`  wrote ${rel}`);
}

