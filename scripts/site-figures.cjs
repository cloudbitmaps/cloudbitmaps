#!/usr/bin/env node
/**
 * Gates the published figures on `site/benchmarks.html` and `site/index.html` against their sources.
 *
 * WHY THIS SCRIPT EXISTS
 *
 * The designed benchmarks page carried the line "Every anchor on this page is asserted in CI, so a regression
 * or an overclaim breaks the build." That was not true — nothing asserted them. It is the worst available kind
 * of overclaim, because it is a claim about our own rigour printed on the one page whose entire purpose is
 * that we do not make claims like that.
 *
 * The options were to delete the sentence or to make it true. This makes it true.
 *
 * WHAT IS CHECKED
 *
 *   1. Every anchor value appears on the page, in the rendered form a reader sees.
 *   2. No unaccounted money figure or crossover rate appears anywhere in the page's visible text — the
 *      inverse direction, without which a check can only catch a MISSING number and never a WRONG one added
 *      beside the right ones. (That hole was real: an earlier version of the /demo gate passed while the page
 *      said 41,208 instead of 100,000, because 100,000 still appeared elsewhere.)
 *   3. The counts in Home's spec strip, derived from the source tree — checked in three directions: the page
 *      drifting from the source, the source drifting from the page, and the entry being deleted outright.
 *
 * SOURCES, and none is hand-maintained:
 *   · bench/results.json      — generated by `pnpm bench` from the shipped estimateCost().
 *   · docs/benchmarks.md      — the unit-economics table, parsed rather than transcribed.
 *   · packages/core/src       — the driver classes themselves, for the backend count.
 *   · packages/roaring/…json  — its declared dependencies, for the third-party count.
 *
 * Usage: node scripts/site-figures.cjs        (report + exit non-zero on any mismatch)
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const RESULTS = path.join(ROOT, 'bench', 'results.json');
const DOC = path.join(ROOT, 'docs', 'benchmarks.md');

const problems = [];
const fail = (m) => problems.push(m);

const results = JSON.parse(fs.readFileSync(RESULTS, 'utf8'));
const doc = fs.readFileSync(DOC, 'utf8');

// ── the three unit-economics anchors, parsed out of the docs table ────────────────────────────────────────
function docAnchor(label) {
  const re = new RegExp(
    `\\|[^|\\n]*${label}[^|\\n]*\\|\\s*\\*\\*\\$([\\d.]+) per million\\*\\*`,
    'i',
  );
  const m = re.exec(doc);
  if (!m) {
    fail(`docs/benchmarks.md no longer states a "per million" cost for ${label}`);
    return null;
  }
  return Number(m[1]);
}
const writeCost = docAnchor('Incremental');
const countCost = docAnchor('count\\(\\)');
const publishCost = docAnchor('Segment publish');

// ── the latency claim, also parsed ────────────────────────────────────────────────────────────────────────
const p50 = /\*\*p50\*\*\s*\|\s*\*\*([\d.]+) ms\*\*/.exec(doc);
const p99 = /\|\s*p99\s*\|\s*\*\*([\d.]+) ms\*\*/.exec(doc);
if (!p50 || !p99) fail('docs/benchmarks.md no longer states the p50/p99 warm has() figures');

// ── the estimator's own accuracy (K3) ─────────────────────────────────────────────────────────────────────
// This is the claim every other figure on the page rests on, since they all come out of estimateCost(). Parsed
// rather than transcribed so that loosening it in the docs cannot leave a tighter number published on the site.
const k3 = /prediction lands within ±(\d+)% of the engine's actual measured/.exec(doc);
if (!k3) fail("docs/benchmarks.md no longer states the estimator's ±N% accuracy claim (K3)");

// ── the real-cloud calibration receipt ────────────────────────────────────────────────────────────────────
// The only figures on the page that are what AWS ACTUALLY CHARGED rather than what the model predicts, so they
// are also the only ones a reader has no way to sanity-check. Every line item, the total, the request count,
// the date and the run id come out of the docs table. Transcribing a receipt by hand is exactly how a page ends
// up quoting a number no run produced.
const calDate = /MEASURED\*\* against real S3 \+ DynamoDB on \*\*(\d{4}-\d{2}-\d{2})\*\*/.exec(doc);
const calRun = /run id `([\w-]+)`/.exec(doc);
if (!calDate || !calRun)
  fail('docs/benchmarks.md no longer dates/identifies the AWS calibration run');

// Line items: `| DynamoDB write | 2,020 WRU | $0.625/M | $0.001263 |` and the bolded Total row.
const calRows = [
  ...doc.matchAll(
    /^\|\s*(?:\*\*)?([\w /]+?)(?:\*\*)?\s*\|\s*(?:\*\*)?([\d,]+(?: \w+)?)(?:\*\*)?\s*\|[^|\n]*\|\s*(?:\*\*)?(\$[\d.]+)(?:\*\*)?\s*\|$/gm,
  ),
]
  .map((m) => ({ term: m[1].trim(), qty: m[2].trim(), cost: m[3] }))
  .filter((r) => /Dynamo|S3|Total/i.test(r.term));
if (calRows.length < 5) {
  fail(
    `docs/benchmarks.md's calibration table parsed to ${calRows.length} rows, expected 5 ` +
      '(4 line items + total) — did its shape change?',
  );
}

// ── the reserved-RAM baseline's SPEC ──────────────────────────────────────────────────────────────────────
// $346 appeared eight times across the site without ever saying what it buys, which made the single most
// load-bearing comparison on the page unauditable: a reader could not tell whether the node was sized for this
// dataset or several times larger than it. The spec is now published, so it gets gated like every other claim.
//
// Source is the pricing profile's own trailing comment in core/cost.ts — the same literal the $346 comes from,
// so the prose cannot drift from the number it describes. Parsed, not transcribed.
const COST = path.join(ROOT, 'packages', 'core', 'src', 'core', 'cost.ts');
const baseline =
  /redis:\s*\{\s*monthlyUSD:\s*(\d+)\s*\}\s*,?\s*\/\/\s*ElastiCache HA:\s*([^;]+);\s*~\$(\d+) single-node/.exec(
    fs.readFileSync(COST, 'utf8'),
  );
if (!baseline) {
  fail(
    'core/cost.ts no longer states the Redis baseline in the expected "ElastiCache HA: <topology>; ~$N single-node" form',
  );
} else if (Number(baseline[1]) !== results.redisBaselineUSD) {
  fail(
    `core/cost.ts says $${baseline[1]}/mo but bench/results.json says $${results.redisBaselineUSD} — re-run \`pnpm bench\``,
  );
}
// e.g. "1 primary + 2 replicas (cache.m7g.large)" -> the node count and the instance class must both be on the page.
const baselineTopology = baseline ? baseline[2].replace(/\s*\([^)]*\)\s*$/, '').trim() : null;
const baselineInstance = baseline ? /\(([\w.]+)\)/.exec(baseline[2])?.[1] : null;

// ── at-rest rounds for display, and the rounding is stated rather than assumed ─────────────────────────────
const atRestExact = results.atRest.monthlyUSD; // 0.0276
const atRestShown = atRestExact.toFixed(2); // "0.03"
if (Number(atRestShown) === 0) fail(`atRest.monthlyUSD (${atRestExact}) rounds to $0.00 at 2dp`);

const anchors = [
  ['1M incremental writes', writeCost === null ? null : `$${writeCost.toFixed(2)}`],
  ['1M count() calls', countCost === null ? null : `$${countCost.toFixed(2)}`],
  ['1M segment publishes', publishCost === null ? null : `$${publishCost.toFixed(2)}`],
  ['at rest, monthly', `$${atRestShown}`],
  ['at rest, size', `${results.atRest.sizeGiB} GiB`],
  ['at rest, % of Redis', `${results.atRest.pctOfRedis}%`],
  ['Redis-HA baseline', `$${results.redisBaselineUSD}`],
  ['write crossover', `${results.writeCrossoverPerSec}`],
  ['read crossover', `${results.readCrossoverPerSec}`],
  ['item size assumption', `${results.assumptions.avgItemKiB} KiB`],
  ['warm has() p50', p50 ? `${p50[1]} ms` : null],
  ['warm has() p99', p99 ? `${p99[1]} ms` : null],
  ['estimator accuracy (K3)', k3 ? `±${k3[1]}%` : null],
  ['baseline topology', baselineTopology],
  ['baseline instance class', baselineInstance],
  ['baseline single-node', baseline ? `$${baseline[3]}` : null],
  ['calibration date', calDate ? calDate[1] : null],
  ['calibration run id', calRun ? calRun[1] : null],
  // Every calibration line item and the total, so the receipt cannot be quietly retyped.
  //
  // Quantities are only anchored when they are DISCRIMINATING — `2,020 WRU`, `6,355 requests`. The S3 rows'
  // quantities are the bare strings "22" and "23", which `includes()` would find in almost any page (a year, a
  // percentage, a pixel value), so anchoring them would add two checks that cannot fail. A gate that always
  // passes is worse than no gate, because it reports coverage it does not have. The cost column carries those
  // two rows instead, and every cost is distinctive to six decimal places.
  ...calRows.flatMap((r) => [
    ...(/[ ,]/.test(r.qty) ? [[`calibration · ${r.term} qty`, r.qty]] : []),
    [`calibration · ${r.term} cost`, r.cost],
  ]),
];

// ── the inverse check now covers HOME as well as /benchmarks ───────────────────────────────────────────────
// The rebuilt home page states, in its own words, that "every money figure and rate on this site is checked in
// CI against the sources that produced it — in both directions". That was FALSE the moment it was written: this
// script only ever read benchmarks.html, and Home quotes eight money figures of its own.
//
// A page claiming our rigour while nothing enforces it is the specific failure this script was created to fix
// (the designed benchmarks page said its anchors were CI-asserted when nothing asserted them). Shipping the same
// error again, on the home page, would be worse than the first time. So the claim is made true instead.
//
// Home is checked for the INVERSE direction only. It is a summary: it is expected to quote a subset, and
// requiring every anchor to appear on it would force the estimator's p50, the calibration run id and the
// crossover topologies onto a page whose job is not to carry them. What must never happen is Home stating a
// figure no source accounts for.
const PAGES = [
  { rel: 'site/benchmarks.html', requireAll: true },
  { rel: 'site/index.html', requireAll: false },
];

for (const page of PAGES) {
  const PAGE_PATH = path.join(ROOT, page.rel);
  let html;
  try {
    html = fs.readFileSync(PAGE_PATH, 'utf8');
  } catch {
    fail(`${page.rel} is missing`);
  }
  if (!html) continue;
  // The inlined crossover chart is stripped out before the prose scan, and then checked separately below.
  //
  // Why: its y-axis ticks are $0/$200/$400/$600 and its curve labels restate the crossovers, so leaving it in
  // made the inverse check fire on four axis labels. Whitelisting those four strings would have been the wrong
  // fix — it widens the allow-list permanently to silence a specific run, and a later Y_MAX change would then
  // introduce new unaccounted figures OR silently pass. The chart is not prose: bench/run.cjs generates it from
  // the same bench/results.json this script reads, so it cannot drift from the anchors independently. What it
  // CAN do is disagree about the crossover it marks, so that is asserted directly.
  const svgs = html.match(/<svg[\s\S]*?<\/svg>/g) || [];

  // Meta descriptions are pulled into the scan explicitly. Stripping tags removes attribute VALUES, so
  // every money figure inside <meta name="description" content="..."> was invisible to the check below —
  // and those strings are the copy a search result and a shared link actually show, which makes them the
  // highest-leverage sentences on the site rather than the lowest. Home currently quotes $0.03 and $346 in
  // three of them.
  const metas = [
    ...html.matchAll(
      /<meta[^>]*(?:name="(?:description|twitter:description)"|property="og:description")[^>]*content="([^"]*)"/g,
    ),
  ]
    .map((m) => m[1])
    .join(' ');

  const visible = html
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<(script|style)[^>]*>[\s\S]*?<\/\1>/g, '')
    .replace(/<svg[\s\S]*?<\/svg>/g, ' ')
    .replace(/<[^>]+>/g, ' ')
    .concat(' ', metas);

  // ── the chart, checked rather than exempted ──────────────────────────────────────────────────────────
  // Mirrors bench/run.cjs's own rounding: one decimal below 100/s, none above.
  const chartLabel = (n) => `crossover ≈ ${n.toFixed(n < 100 ? 1 : 0)} /s`;
  const chart = svgs.find((s) => s.includes('crossover'));
  if (page.requireAll && !chart) {
    fail(
      'benchmarks.html no longer inlines the crossover chart — run `pnpm bench` to refill BENCH:CHART',
    );
  } else if (chart) {
    for (const [what, want] of [
      ['the write crossover', chartLabel(results.writeCrossoverPerSec)],
      ['the read crossover', chartLabel(results.readCrossoverPerSec)],
      ['the Redis baseline', `$${results.redisBaselineUSD}/mo`],
    ]) {
      if (!chart.includes(want)) {
        fail(`the inlined chart does not mark ${what} (${want}) — stale? re-run \`pnpm bench\``);
      }
    }
  }

  // 1 · every anchor must be stated — on /benchmarks, which is the page that owns them
  if (page.requireAll) {
    for (const [name, want] of anchors) {
      if (want === null) continue;
      if (!visible.includes(want)) fail(`${page.rel} never states ${name} (${want})`);
    }
  }

  // 2 · and nothing else that looks like money or a rate may appear
  const allowed = new Set(anchors.map(([, v]) => v).filter(Boolean));
  // The page legitimately restates figures owned by other pages' gates; each is listed so that adding one is
  // a deliberate act rather than a silent widening.
  const alsoAllowed = new Set([
    '$0.03', // at-rest, the rounded form
    '100', // chunks fetched — gated by site-replay.cjs
    '2,000', // chunks per segment — same
    '25.3 ms', // intersect wall time — same
    '1,900', // chunks skipped per segment — same
    // Home only. "$0" is the standing charge — the ABSENCE of a charge, which is the whole pitch of layer 03.
    // There is no source that could "account for" zero, and demanding one would be the check misfiring on the
    // one figure that needs no evidence.
    '$0',
  ]);
  const money = visible.match(/\$[\d,]+(?:\.\d+)?/g) || [];
  for (const m of new Set(money)) {
    if (!allowed.has(m) && !alsoAllowed.has(m)) {
      fail(`${page.rel} states ${m}, which no source accounts for`);
    }
  }
}

// ── the spec strip on Home, derived from the source tree ───────────────────────────────────────────────────
// `3 tiers · 10 drivers · 1 third-party dependency` sits under the keys figure on Home. Home is now the ONLY
// page that states the driver count — it used to also sit in the final section's meta line, and consolidating
// it there left the figure with nothing holding it true. That is the exact shape of the failure this script was
// written for: a number on a page with no source behind it.
//
// `3 tiers` is deliberately NOT anchored. Hot/warm/cold is the architecture — it cannot drift without a rewrite
// that would touch every page and every doc, so a check for it is one that CANNOT FAIL, the same reason the
// bare "22"/"23" calibration quantities above are left out. Two of the three figures can drift silently while
// CI stays green, and those are the two derived below.
const specAnchors = [];
{
  // Registry drivers are excluded on purpose: they store the segment registry, not bitmap chunks, and are a
  // separate axis from the tiering the page is describing. `Memory` is the in-process dev/test pair, `Retrying`
  // is a decorator wrapping another driver — neither is a backend a reader could point at.
  const NOT_A_BACKEND = new Set(['memory', 'retrying']);
  const backends = new Set();
  const walk = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) walk(p);
      else if (e.name.endsWith('.ts')) {
        for (const m of fs
          .readFileSync(p, 'utf8')
          .matchAll(/export class (\w+?)(?:Warm|Cold)\w*Driver\b/g)) {
          const backend = m[1].toLowerCase();
          if (!NOT_A_BACKEND.has(backend)) backends.add(backend);
        }
      }
    }
  };
  walk(path.join(ROOT, 'packages', 'core', 'src'));

  // Without this the check is vacuous in the one case that matters most: a refactor that moves or renames the
  // driver classes makes the regex match nothing, and a count of 0 would then "disagree" in a way someone could
  // silence by editing the page rather than the derivation.
  if (backends.size === 0) {
    fail(
      'the driver-count derivation matched no `export class …WarmDriver/…ColdDriver` under packages/core/src — ' +
        'the classes moved or were renamed, so this check is no longer measuring anything',
    );
  }

  // Only `roaring` is somebody else's code; `@cloudbitmaps/core` is ours and is declared `workspace:*`. This is
  // what makes the page's wording "third-party dependency" true where a bare "runtime dependency" would not be.
  const roaringPkg = JSON.parse(
    fs.readFileSync(path.join(ROOT, 'packages', 'roaring', 'package.json'), 'utf8'),
  );
  const thirdParty = Object.entries(roaringPkg.dependencies || {})
    .filter(([, v]) => !String(v).startsWith('workspace:'))
    .map(([n]) => n);

  const homeHtml = fs.readFileSync(path.join(ROOT, 'site', 'index.html'), 'utf8');

  // ── the default warm-scan ceiling, wherever the site quotes it ─────────────────────────────────────────
  // /architecture and /usage now publish this because the pages state the COLD footprint formula precisely and
  // used to say nothing at all about Warm — and Warm is a separate term outside that window, one per operand.
  // A reader sizing a function for a many-operand intersection needs both, so the figure had to be published;
  // and once published it needs a source, or it becomes the next stale number on the site.
  const engineSrc = fs.readFileSync(
    path.join(ROOT, 'packages', 'core', 'src', 'core', 'engine.ts'),
    'utf8',
  );
  const scanCap = /DEFAULT_MAX_WARM_SCAN_BYTES\s*=\s*(\d+)\s*\*\s*1024\s*\*\s*1024\b/.exec(
    engineSrc,
  );
  if (!scanCap) {
    fail(
      'engine.ts no longer defines DEFAULT_MAX_WARM_SCAN_BYTES as `N * 1024 * 1024` — the site quotes this ' +
        'ceiling in MiB, so either the constant changed shape or the derivation needs updating',
    );
  } else {
    const want = `${scanCap[1]} MiB`;
    for (const rel of ['site/architecture.html', 'site/usage.html']) {
      const html = fs.readFileSync(path.join(ROOT, rel), 'utf8');
      // Only assert on the page that actually quotes a figure; /usage names the option without a number.
      if (/maxWarmScanBytes/.test(html) && /\d+ MiB/.test(html) && !html.includes(want)) {
        fail(
          `${rel} quotes a warm-scan ceiling that is not ${want} (engine.ts's DEFAULT_MAX_WARM_SCAN_BYTES)`,
        );
      }
    }
    specAnchors.push(['default warm-scan ceiling', want]);
  }

  // ── the encoding benchmark's factors, wherever /flavors/roaring quotes them ─────────────────────────────
  // That page's table argued adaptivity and offered nothing to check it against — and its "array, bitset and run"
  // row was not even true of the shipped codec until 0.6.0, because roaring's run form takes an explicit pass
  // nothing was making. The factors are published now, so they get a source like every other figure here.
  //
  // ONE rounding rule, computed here rather than transcribed: >=10x rounds to an integer, below that to 2dp.
  // An ad-hoc mix (543 truncated, 63 rounded up, 1.88 to 2dp) is how a gate ends up encoding a typo as a spec.
  const encoding = JSON.parse(
    fs.readFileSync(path.join(ROOT, 'bench', 'encoding-results.json'), 'utf8'),
  );
  const roaringPage = fs.readFileSync(path.join(ROOT, 'site', 'flavors', 'roaring.html'), 'utf8');
  const show = (ratio) => (ratio >= 10 ? String(Math.round(ratio)) : ratio.toFixed(2));
  for (const shape of encoding.shapes) {
    // A shape roaring LOSES is displayed as its reciprocal — the page says "1.02x larger", not "0.98x smaller",
    // because a reader should not have to invert a number to learn we came second.
    const want = shape.roaringSmaller
      ? `${show(shape.vsBestFixed)}\u00d7 smaller`
      : `${show(1 / shape.vsBestFixed)}\u00d7 larger`;
    // Match the WHOLE claim, direction included. An earlier version stripped "smaller"/"larger" and compared
    // only the digits — so the page could have said a shape roaring LOSES was "1.02x smaller" and this would
    // have passed. The direction is the claim; a gate that checks the number but not which way it points is
    // exactly the kind of check that reports coverage it does not have.
    if (!roaringPage.includes(want)) {
      fail(
        `site/flavors/roaring.html does not state the measured factor for the "${shape.shape}" shape ` +
          `as "${want}" — re-run \`pnpm bench:encoding\` and update the page together`,
      );
    } else {
      specAnchors.push([`encoding \u00b7 ${shape.shape}`, want]);
    }
  }

  // ── the soak's combine evidence, where /benchmarks cites it ────────────────────────────────────────────
  // Limitation 04 on that page used to read "the intersection window is not soak-tested", which was true. It now
  // cites two measured figures instead, so they get a source like every other number on the site — the whole
  // point of this file is that no figure is published on the strength of someone having once seen it.
  //
  // The native-creep figure is the load-bearing one. It is the off-heap byte count the roaring addon actually
  // holds, which is where a combine leak WOULD show up and where a JS-heap sample would miss it, so it is quoted
  // to 2dp rather than as "flat" — a reader can tell 0.00 from 0.05, and "flat" hides which one it was.
  const soak = JSON.parse(fs.readFileSync(path.join(ROOT, 'bench', 'soak-results.json'), 'utf8'));
  const benchPage = fs.readFileSync(path.join(ROOT, 'site', 'benchmarks.html'), 'utf8');
  if (soak.combines === undefined) {
    fail(
      'bench/soak-results.json has no `combines` field — it predates the combine phase. Re-run `pnpm soak` ' +
        'with SOAK_INJECT=1; a results file from before that phase existed cannot evidence limitation 04.',
    );
  } else if (soak.combines === 0) {
    // The soak itself refuses to report PASS on zero combines, but the *site* must not be able to cite a
    // zero-combine run as evidence either — that would launder "we did not test it" into a published number.
    fail(
      'bench/soak-results.json records 0 combines — /benchmarks must not cite it as combine evidence',
    );
  } else {
    for (const [label, want] of [
      ['soak · combines', String(soak.combines)],
      ['soak · native creep', `${soak.nativeCreepMiB.toFixed(2)} MiB`],
    ]) {
      if (!benchPage.includes(want)) {
        fail(
          `site/benchmarks.html does not state "${want}" (${label}) — re-run \`pnpm soak\` with ` +
            `SOAK_INJECT=1 and update limitation 04 together`,
        );
      } else {
        specAnchors.push([label, want]);
      }
    }
  }

  // ── the invariant count ────────────────────────────────────────────────────────────────────────────────
  // Home's correctness panel used to close on "1,156 of them run on every commit". That was ungated AND already
  // wrong — the suite was at 1,161. An exact test total is the worst figure to publish: it moves on nearly every
  // commit, so gating it breaks CI for anyone who adds a test, and not gating it leaves it stale within a day.
  //
  // The invariant count is the stable number and the one the claim actually rests on, so the page states that
  // instead. CLAUDE.md's "Hard correctness invariants" section is the only enumeration of them in the repo,
  // which makes it the source.
  const claudeMd = fs.readFileSync(path.join(ROOT, 'CLAUDE.md'), 'utf8');
  const invariantSection = /## Hard correctness invariants\n([\s\S]*?)(?=\n## |$)/.exec(claudeMd);
  let invariantCount = 0;
  if (!invariantSection) {
    fail('CLAUDE.md no longer has a "## Hard correctness invariants" section to count');
  } else {
    invariantCount = (invariantSection[1].match(/^\d+\. \*\*/gm) || []).length;
    if (invariantCount === 0) {
      fail(
        "CLAUDE.md's invariants section parsed to 0 numbered items — its list formatting changed, so this " +
          'check is no longer measuring anything',
      );
    }
    const foot = /<p class="ba-foot">([\s\S]*?)<\/p>/.exec(homeHtml);
    if (!foot) {
      fail('site/index.html no longer carries the .ba-foot line that states the invariant count');
    } else {
      const stated = /<strong>(\d+)\s+hard correctness invariants<\/strong>/.exec(foot[1]);
      if (!stated) {
        fail("Home's correctness panel no longer states an invariant count");
      } else if (Number(stated[1]) !== invariantCount) {
        fail(
          `Home says ${stated[1]} hard correctness invariants but CLAUDE.md enumerates ${invariantCount}`,
        );
      } else {
        specAnchors.push(['Home · hard invariants', String(invariantCount)]);
      }
    }
  }

  const strip = /<p class="keys-stats">([\s\S]*?)<\/p>/.exec(homeHtml);
  if (!strip) {
    fail('site/index.html no longer carries the .keys-stats strip that states the driver count');
  } else {
    const stated = new Map();
    for (const m of strip[1].matchAll(/<strong>([\d,]+)<\/strong>\s*([^<]+?)\s*<\/span>/g)) {
      stated.set(m[2].trim(), Number(m[1].replace(/,/g, '')));
    }
    // Checked in BOTH directions, which is the flaw every earlier gate on this site shipped with. Comparing a
    // derived count against a stated one fails when a driver is added and the page is not updated, AND when the
    // page's number is edited away from the truth. `stated.has` covers the third case — the entry being deleted
    // outright, which an equality check alone would never see because there would be nothing to compare.
    for (const [label, want, detail] of [
      ['drivers', backends.size, () => [...backends].sort().join(', ')],
      ['third-party dependency', thirdParty.length, () => thirdParty.join(', ')],
    ]) {
      if (!stated.has(label)) {
        fail(`Home's spec strip no longer states "${label}"`);
      } else if (stated.get(label) !== want) {
        fail(`Home says ${stated.get(label)} ${label} but the source has ${want}: ${detail()}`);
      } else {
        specAnchors.push([`Home · ${label}`, String(want)]);
      }
    }
  }

  // ── the SAME two counts in the hero's meta line ────────────────────────────────────────────────────────
  // Consolidating these into the spec strip came with the claim that each was then "stated once". That was
  // wrong: only the final section's meta line was checked, and the HERO carries them too — in prime position,
  // and in the loose wording ("1 runtime dependency") that the strip had already been corrected away from.
  //
  // Two statements of a figure is fine where they serve different readers, and these do: at-a-glance in the
  // hero, in context beside the tiering further down. What is not fine is one of them being ungated, which is
  // two chances to drift and one place that notices. Both are covered now.
  const heroMeta = /<p class="meta">([\s\S]*?)<\/p>/.exec(homeHtml);
  if (!heroMeta) {
    fail("site/index.html no longer carries the hero's meta line");
  } else {
    for (const [label, want, detail] of [
      ['storage drivers', backends.size, () => [...backends].sort().join(', ')],
      ['third-party dependency', thirdParty.length, () => thirdParty.join(', ')],
    ]) {
      const m = new RegExp(`(\\d+)\\s+${label}`).exec(heroMeta[1]);
      if (!m) {
        fail(`Home's hero meta line no longer states a count for "${label}"`);
      } else if (Number(m[1]) !== want) {
        fail(
          `Home's hero says ${m[1]} ${label} but the source has ${want}: ${detail()} — the spec strip and ` +
            'the hero must agree, and both must agree with the tree',
        );
      } else {
        specAnchors.push([`Home hero · ${label}`, String(want)]);
      }
    }
  }
}

if (problems.length) {
  console.error('site-figures: the site disagrees with its sources:');
  for (const p of problems) console.error(`  - ${p}`);
  console.error(
    '\n  Sources: bench/results.json (regenerate with `pnpm bench`) · docs/benchmarks.md',
  );
  process.exit(1);
}

