#!/usr/bin/env node
/**
 * Gates the cost anchors on `site/benchmarks.html` against their sources.
 *
 * WHY THIS SCRIPT EXISTS
 *
 * The designed benchmarks page carried the line "Every anchor on this page is asserted in CI, so a regression
 * or an overclaim breaks the build." That was not true — nothing asserted them. It is the worst available kind
 * of overclaim, because it is a claim about our own rigour printed on the one page whose entire purpose is
 * that we do not make claims like that.
 *
 * The options were to delete the sentence or to make it true. This makes it true.
 *
 * WHAT IS CHECKED
 *
 *   1. Every anchor value appears on the page, in the rendered form a reader sees.
 *   2. No unaccounted money figure or crossover rate appears anywhere in the page's visible text — the
 *      inverse direction, without which a check can only catch a MISSING number and never a WRONG one added
 *      beside the right ones. (That hole was real: an earlier version of the /demo gate passed while the page
 *      said 41,208 instead of 100,000, because 100,000 still appeared elsewhere.)
 *
 * SOURCES, and neither is hand-maintained:
 *   · bench/results.json      — generated by `pnpm bench` from the shipped estimateCost().
 *   · docs/benchmarks.md      — the unit-economics table, parsed rather than transcribed.
 *
 * Usage: node scripts/site-figures.cjs        (report + exit non-zero on any mismatch)
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const PAGE = path.join(ROOT, 'site', 'benchmarks.html');
const RESULTS = path.join(ROOT, 'bench', 'results.json');
const DOC = path.join(ROOT, 'docs', 'benchmarks.md');

const problems = [];
const fail = (m) => problems.push(m);

const results = JSON.parse(fs.readFileSync(RESULTS, 'utf8'));
const doc = fs.readFileSync(DOC, 'utf8');

// ── the three unit-economics anchors, parsed out of the docs table ────────────────────────────────────────
function docAnchor(label) {
  const re = new RegExp(
    `\\|[^|\\n]*${label}[^|\\n]*\\|\\s*\\*\\*\\$([\\d.]+) per million\\*\\*`,
    'i',
  );
  const m = re.exec(doc);
  if (!m) {
    fail(`docs/benchmarks.md no longer states a "per million" cost for ${label}`);
    return null;
  }
  return Number(m[1]);
}
const writeCost = docAnchor('Incremental');
const countCost = docAnchor('count\\(\\)');
const publishCost = docAnchor('Segment publish');

// ── the latency claim, also parsed ────────────────────────────────────────────────────────────────────────
const p50 = /\*\*p50\*\*\s*\|\s*\*\*([\d.]+) ms\*\*/.exec(doc);
const p99 = /\|\s*p99\s*\|\s*\*\*([\d.]+) ms\*\*/.exec(doc);
if (!p50 || !p99) fail('docs/benchmarks.md no longer states the p50/p99 warm has() figures');

// ── at-rest rounds for display, and the rounding is stated rather than assumed ─────────────────────────────
const atRestExact = results.atRest.monthlyUSD; // 0.0276
const atRestShown = atRestExact.toFixed(2); // "0.03"
if (Number(atRestShown) === 0) fail(`atRest.monthlyUSD (${atRestExact}) rounds to $0.00 at 2dp`);

const anchors = [
  ['1M incremental writes', writeCost === null ? null : `$${writeCost.toFixed(2)}`],
  ['1M count() calls', countCost === null ? null : `$${countCost.toFixed(2)}`],
  ['1M segment publishes', publishCost === null ? null : `$${publishCost.toFixed(2)}`],
  ['at rest, monthly', `$${atRestShown}`],
  ['at rest, size', `${results.atRest.sizeGiB} GiB`],
  ['at rest, % of Redis', `${results.atRest.pctOfRedis}%`],
  ['Redis-HA baseline', `$${results.redisBaselineUSD}`],
  ['write crossover', `${results.writeCrossoverPerSec}`],
  ['read crossover', `${results.readCrossoverPerSec}`],
  ['item size assumption', `${results.assumptions.avgItemKiB} KiB`],
  ['warm has() p50', p50 ? `${p50[1]} ms` : null],
  ['warm has() p99', p99 ? `${p99[1]} ms` : null],
];

let html;
try {
  html = fs.readFileSync(PAGE, 'utf8');
} catch {
  fail(`${path.relative(ROOT, PAGE)} is missing`);
}

if (html) {
  // The inlined crossover chart is stripped out before the prose scan, and then checked separately below.
  //
  // Why: its y-axis ticks are $0/$200/$400/$600 and its curve labels restate the crossovers, so leaving it in
  // made the inverse check fire on four axis labels. Whitelisting those four strings would have been the wrong
  // fix — it widens the allow-list permanently to silence a specific run, and a later Y_MAX change would then
  // introduce new unaccounted figures OR silently pass. The chart is not prose: bench/run.cjs generates it from
  // the same bench/results.json this script reads, so it cannot drift from the anchors independently. What it
  // CAN do is disagree about the crossover it marks, so that is asserted directly.
  const svgs = html.match(/<svg[\s\S]*?<\/svg>/g) || [];
  const visible = html
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<(script|style)[^>]*>[\s\S]*?<\/\1>/g, '')
    .replace(/<svg[\s\S]*?<\/svg>/g, ' ')
    .replace(/<[^>]+>/g, ' ');

  // ── the chart, checked rather than exempted ──────────────────────────────────────────────────────────
  // Mirrors bench/run.cjs's own rounding: one decimal below 100/s, none above.
  const chartLabel = (n) => `crossover ≈ ${n.toFixed(n < 100 ? 1 : 0)} /s`;
  const chart = svgs.find((s) => s.includes('crossover'));
  if (!chart) {
    fail(
      'benchmarks.html no longer inlines the crossover chart — run `pnpm bench` to refill BENCH:CHART',
    );
  } else {
    for (const [what, want] of [
      ['the write crossover', chartLabel(results.writeCrossoverPerSec)],
      ['the read crossover', chartLabel(results.readCrossoverPerSec)],
      ['the Redis baseline', `$${results.redisBaselineUSD}/mo`],
    ]) {
      if (!chart.includes(want)) {
        fail(`the inlined chart does not mark ${what} (${want}) — stale? re-run \`pnpm bench\``);
      }
    }
  }

  // 1 · every anchor must be stated
  for (const [name, want] of anchors) {
    if (want === null) continue;
    if (!visible.includes(want)) fail(`benchmarks.html never states ${name} (${want})`);
  }

  // 2 · and nothing else that looks like money or a rate may appear
  const allowed = new Set(anchors.map(([, v]) => v).filter(Boolean));
  // The page legitimately restates figures owned by other pages' gates; each is listed so that adding one is
  // a deliberate act rather than a silent widening.
  const alsoAllowed = new Set([
    '$0.03', // at-rest, the rounded form
    '100', // chunks fetched — gated by site-replay.cjs
    '2,000', // chunks per segment — same
    '25.3 ms', // intersect wall time — same
    '1,900', // chunks skipped per segment — same
  ]);
  const money = visible.match(/\$[\d,]+(?:\.\d+)?/g) || [];
  for (const m of new Set(money)) {
    if (!allowed.has(m) && !alsoAllowed.has(m)) {
      fail(`benchmarks.html states ${m}, which no source accounts for`);
    }
  }
}

if (problems.length) {
  console.error('site-figures: benchmarks.html disagrees with its sources:');
  for (const p of problems) console.error(`  - ${p}`);
  console.error(
    '\n  Sources: bench/results.json (regenerate with `pnpm bench`) · docs/benchmarks.md',
  );
  process.exit(1);
}

console.log(
  `site-figures: ${anchors.filter(([, v]) => v).length} anchors verified against their sources.`,
);
for (const [name, v] of anchors) if (v) console.log(`  ${name.padEnd(24)} ${v}`);
